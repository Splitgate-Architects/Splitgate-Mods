function OnMatchFound(MatchAddress)
    local LeaInstr = MatchAddress + 0xA
    local NextInstr = LeaInstr + 0x7
    local Offset = LeaInstr + 0x3
    local ObjObjectsAddr = NextInstr + DerefToInt32(Offset)
